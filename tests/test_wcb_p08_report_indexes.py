"""WC-B P-08: diag_reports.student_id has ONE index in the model - the one production has (``idx_diag_reports_student``, migration 001).

The column used to say ``index=True`` AND the table declared ``Index("idx_diag_reports_student", ...)``: a database built by ``create_all`` (the test
databases, an autogenerated migration) got two indexes on the same column, production one."""
from __future__ import annotations

from src.models.diag_models import DiagReport


def test_student_id_of_reports_has_exactly_one_index_and_it_is_the_production_one():
    on_student = [ix for ix in DiagReport.__table__.indexes if [c.name for c in ix.columns] == ["student_id"]]
    print(f"\nP-08 indexes on diag_reports.student_id: 2 -> {len(on_student)}")
    assert [ix.name for ix in on_student] == ["idx_diag_reports_student"]
    assert not DiagReport.__table__.c.student_id.index


def test_the_other_columns_keep_their_declared_indexes():
    names = {ix.name for ix in DiagReport.__table__.indexes}
    assert "idx_diag_reports_student" in names
    assert DiagReport.__table__.c.session_id.unique                       # the unique constraint of the session is untouched
